CREATE PROCEDURE SP_CERRAR_PRESUPUESTO (
    p_id_presupuesto INTEGER,
    p_modificado_por INTEGER
)
RETURNS (
    total_ingresos NUMERIC(15, 2),
    total_gastos NUMERIC(15, 2),
    total_ahorros NUMERIC(15, 2),
    balance_final NUMERIC(15, 2)
)
AS
DECLARE VARIABLE v_estado VARCHAR(20);
DECLARE VARIABLE v_anio_fin INTEGER;
DECLARE VARIABLE v_mes_fin INTEGER;
DECLARE VARIABLE v_anio_actual INTEGER;
DECLARE VARIABLE v_mes_actual INTEGER;
DECLARE VARIABLE v_id_usuario INTEGER;
DECLARE VARIABLE v_monto_ingresos NUMERIC(15, 2);
DECLARE VARIABLE v_monto_gastos NUMERIC(15, 2);
DECLARE VARIABLE v_monto_ahorros NUMERIC(15, 2);
BEGIN
    SELECT estado, anio_fin, mes_fin, id_usuario
    FROM PRESUPUESTO
    WHERE id_presupuesto = :p_id_presupuesto
    INTO :v_estado, :v_anio_fin, :v_mes_fin, :v_id_usuario;

    IF (v_estado IS NULL) THEN
        EXCEPTION ex_presupuesto_no_encontrado;

    IF (v_estado = 'cerrado') THEN
        EXCEPTION ex_presupuesto_estado;

    v_anio_actual = EXTRACT(YEAR FROM CURRENT_DATE);
    v_mes_actual = EXTRACT(MONTH FROM CURRENT_DATE);

    IF ((v_anio_actual * 100 + v_mes_actual) < (v_anio_fin * 100 + v_mes_fin)) THEN
        EXCEPTION ex_presupuesto_no_finalizado;

    SELECT
        COALESCE(SUM(CASE WHEN tipo = 'ingreso' THEN monto ELSE 0 END), 0),
        COALESCE(SUM(CASE WHEN tipo = 'gasto' THEN monto ELSE 0 END), 0),
        COALESCE(SUM(CASE WHEN tipo = 'ahorro' THEN monto ELSE 0 END), 0)
    FROM TRANSACCIONES
    WHERE presupuesto_id = :p_id_presupuesto
      AND estado = 'activo'
    INTO :v_monto_ingresos, :v_monto_gastos, :v_monto_ahorros;

    UPDATE PRESUPUESTO
    SET estado = 'cerrado',
        modificado_en = CURRENT_TIMESTAMP,
        modificado_por = :p_modificado_por
    WHERE id_presupuesto = :p_id_presupuesto;

    total_ingresos = v_monto_ingresos;
    total_gastos = v_monto_gastos;
    total_ahorros = v_monto_ahorros;
    balance_final = v_monto_ingresos - v_monto_gastos - v_monto_ahorros;

    SUSPEND;
END#


CREATE PROCEDURE SP_CREAR_PRESUPUESTO_COMPLETO (
    p_id_usuario INTEGER,
    p_nombre VARCHAR(255),
    p_descripcion VARCHAR(500),
    p_anio_inicio INTEGER,
    p_mes_inicio INTEGER,
    p_anio_fin INTEGER,
    p_mes_fin INTEGER,
    p_total_ingresos NUMERIC(15,2),
    p_total_gastos NUMERIC(15,2),
    p_total_ahorro NUMERIC(15,2),
    p_creado_por INTEGER
)
RETURNS (
    id_presupuesto INTEGER
)
AS
DECLARE VARIABLE v_estado VARCHAR(20);
DECLARE VARIABLE v_fecha_creacion TIMESTAMP;
DECLARE VARIABLE v_overlap INTEGER;
BEGIN
    v_estado = 'activo';
    v_fecha_creacion = CURRENT_TIMESTAMP;

    IF (p_anio_fin < p_anio_inicio) THEN
        EXCEPTION ex_presupuesto_vigencia;

    IF (p_anio_fin = p_anio_inicio AND p_mes_fin < p_mes_inicio) THEN
        EXCEPTION ex_presupuesto_vigencia;

    SELECT COUNT(1)
    FROM PRESUPUESTO
    WHERE id_usuario = :p_id_usuario
      AND estado = 'activo'
      AND ((anio_inicio * 100 + mes_inicio) <= (p_anio_fin * 100 + p_mes_fin))
      AND ((anio_fin * 100 + mes_fin) >= (p_anio_inicio * 100 + p_mes_inicio))
    INTO :v_overlap;

    IF (v_overlap > 0) THEN
        EXCEPTION ex_presupuesto_traslapado;

    INSERT INTO PRESUPUESTO (
        id_usuario,
        nombre_presupuesto,
        anio_inicio,
        mes_inicio,
        anio_fin,
        mes_fin,
        total_ingresos_planificados,
        total_gastos_planificados,
        total_ahorro_planificado,
        fecha_creacion,
        estado,
        creado_en,
        creado_por
    ) VALUES (
        :p_id_usuario,
        :p_nombre,
        :p_anio_inicio,
        :p_mes_inicio,
        :p_anio_fin,
        :p_mes_fin,
        :p_total_ingresos,
        :p_total_gastos,
        :p_total_ahorro,
        :v_fecha_creacion,
        :v_estado,
        CURRENT_TIMESTAMP,
        :p_creado_por
    )
    RETURNING id_presupuesto INTO :id_presupuesto;

    SUSPEND;
END#


